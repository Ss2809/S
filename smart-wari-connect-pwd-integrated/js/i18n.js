/* ===================== Smart Wari Connect — i18n runtime ===================== */
(function () {
  var LANG_KEY = 'swc_lang';
  var LANG_NAMES = { en: 'English', hi: 'हिंदी', mr: 'मराठी' };

  function getLang() {
    return localStorage.getItem(LANG_KEY) || 'en';
  }

  function setLang(lang) {
    localStorage.setItem(LANG_KEY, lang);
  }

  function t(key, lang) {
    var table = TRANSLATIONS[lang] || TRANSLATIONS.en;
    if (table && table[key] !== undefined) return table[key];
    // fallback to English if a translation is missing for this key
    if (TRANSLATIONS.en && TRANSLATIONS.en[key] !== undefined) return TRANSLATIONS.en[key];
    return null;
  }

  function applyLanguage(lang) {
    document.documentElement.setAttribute('lang', lang === 'en' ? 'en' : lang);
    document.documentElement.setAttribute('data-app-lang', lang);

    document.querySelectorAll('[data-i18n]').forEach(function (el) {
      var key = el.getAttribute('data-i18n');
      var val = t(key, lang);
      if (val !== null) el.textContent = val;
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach(function (el) {
      var key = el.getAttribute('data-i18n-placeholder');
      var val = t(key, lang);
      if (val !== null) el.setAttribute('placeholder', val);
    });

    document.querySelectorAll('[data-i18n-title]').forEach(function (el) {
      var key = el.getAttribute('data-i18n-title');
      var val = t(key, lang);
      if (val !== null) el.setAttribute('title', val);
    });

    document.querySelectorAll('[data-i18n-aria-label]').forEach(function (el) {
      var key = el.getAttribute('data-i18n-aria-label');
      var val = t(key, lang);
      if (val !== null) el.setAttribute('aria-label', val);
    });

    // reflect active language in every language dropdown on the page
    document.querySelectorAll('.lang-option').forEach(function (opt) {
      opt.classList.toggle('active', opt.getAttribute('data-lang') === lang);
    });
    document.querySelectorAll('.lang-switch .icon-btn').forEach(function (btn) {
      btn.setAttribute('title', 'Change language · ' + (LANG_NAMES[lang] || lang));
    });
  }

  function init() {
    var current = getLang();
    applyLanguage(current);

    document.querySelectorAll('.lang-option').forEach(function (opt) {
      opt.addEventListener('click', function (e) {
        e.preventDefault();
        var lang = opt.getAttribute('data-lang');
        setLang(lang);
        applyLanguage(lang);
      });
    });
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', init);
  } else {
    init();
  }

  // expose for debugging / manual use
  window.SmartWariI18n = { setLang: function (l) { setLang(l); applyLanguage(l); }, getLang: getLang };
})();
